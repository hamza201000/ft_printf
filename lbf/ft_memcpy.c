#include "libft.h"

void	*ft_memcpy(void *dest, const void *src, size_t n)
{
	char		*new_dest;
	const char	*new_src;
	size_t		i;

	if (!dest)
		return (NULL);
	else if (!src)
		return (dest);
	new_dest = dest;
	new_src = src;
	i = 0;
	while (i < n)
	{
		new_dest[i] = new_src[i];
		i++;
	}
	return (dest);
}
